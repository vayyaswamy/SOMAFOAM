"""Source terms of the manufactured solution of examples/verification/manufacturedSolution2D.

    python3 generate.py

writes applications/verification/mmsPlasma2D/mmsSolution.H with the exact
fields and the source terms as C++ functions of (x, y). Requires sympy.

The problem is steady and dimensionless on the unit square. With the
potential V, the ion density n and the electron energy density w,

    -div(grad V)                              = S_V
    div(n u_i - D_i grad n)                   = S_n,   u_i = -mu_i grad V
    div(w u_e - D_e grad w)                   = S_w,   u_e =  mu_e grad V

with D_i = 1 and the variable coefficient D_e = 1 + x y/2. The drift terms
are linear in the mobilities, so each source is written as a diffusion part
plus mu times a drift part, and the mobilities are set in system/mmsDict.
The factor 5/3 of the electron energy flux multiplies both sides of the
steady equation and is left out.
"""
import os
import re
import sympy as sp

x, y = sp.symbols("x y", real=True)
pi = sp.pi

V = sp.Rational(1, 2) * sp.sin(pi * x) * sp.cos(pi * y) + x * y
n = sp.exp(x / 2) * (1 + sp.Rational(2, 5) * sp.sin(pi * x) * sp.sin(pi * y))
w = sp.Rational(3, 2) + sp.Rational(1, 2) * sp.cos(pi * x) * sp.cos(pi * y) + y / 5
De = 1 + x * y / 2


def div(fx, fy):
    return sp.diff(fx, x) + sp.diff(fy, y)


def grad(f):
    return sp.diff(f, x), sp.diff(f, y)


gV = grad(V)
S_V = -div(*gV)

# Ions: n u_i = -mu_i n grad V
S_n_diff = -div(*grad(n))
S_n_drift = div(-n * gV[0], -n * gV[1])

# Electron energy: w u_e = mu_e w grad V
gw = grad(w)
S_w_diff = -div(De * gw[0], De * gw[1])
S_w_drift = div(w * gV[0], w * gV[1])

funcs = [
    ("Vexact", V), ("nExact", n), ("wExact", w), ("DeExact", De),
    ("SV", S_V),
    ("SnDiff", S_n_diff), ("SnDrift", S_n_drift),
    ("SwDiff", S_w_diff), ("SwDrift", S_w_drift),
]

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "..", "..", "applications", "verification", "mmsPlasma2D", "mmsSolution.H")

with open(out, "w") as f:
    f.write("// Generated by examples/verification/manufacturedSolution2D/generate.py.\n")
    f.write("// Do not edit; rerun the script after changing the solution.\n\n")
    f.write("#ifndef mmsSolution_H\n#define mmsSolution_H\n\n#include <cmath>\n\n")
    f.write("namespace mms\n{\n\n")
    for name, expr in funcs:
        code = sp.ccode(sp.simplify(expr)).replace("M_PI", "3.14159265358979323846")
        for fn in ("sin", "cos", "exp", "pow"):
            code = re.sub(r"(?<![\w:])" + fn + r"\(", "std::" + fn + "(", code)
        f.write(f"inline double {name}(const double x, const double y)\n{{\n")
        f.write(f"    return {code};\n}}\n\n")
    f.write("} // End namespace mms\n\n#endif\n")

print("wrote", os.path.normpath(out))
